"""
ChainSync Core Data Models
Implements shared schemas for Transactions, Blocks, Events, and Semaphore States.
Compatible with the project plan specification and Chapter 17/18 schemas.
"""

from enum import Enum
from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field
from core.crypto import (
    canonical_json_bytes,
    sha256_hex,
    verify_signature,
    KeyPair,
    MerkleTree
)


class TransactionType(str, Enum):
    CREATE = "CREATE"
    ACQUIRE = "ACQUIRE"
    RELEASE = "RELEASE"
    RENEW = "RENEW"
    TICK = "TICK"


class Transaction(BaseModel):
    """
    A ChainSync transaction signed by a client or issued by the block leader (TICK).
    """
    type: TransactionType
    semaphore: str = ""
    capacity: Optional[int] = None      # Used in CREATE (1 = mutex, N = counting)
    lease_ms: Optional[int] = None     # Used in ACQUIRE, RENEW
    token: Optional[int] = None        # Used in RELEASE, RENEW
    request_id: str = ""               # Client-generated UUID/hex for idempotency
    nonce: int = 0                     # Monotonic counter per sender
    chain_id: str = "chainsync-dev"    # Network replay protection
    sender: str = ""                   # Public key hex
    signature: str = ""                # Ed25519 signature hex

    def signable_dict(self) -> Dict[str, Any]:
        """Dictionary of fields included in cryptographic signature."""
        return {
            "type": self.type.value if isinstance(self.type, TransactionType) else str(self.type),
            "semaphore": self.semaphore,
            "capacity": self.capacity,
            "lease_ms": self.lease_ms,
            "token": self.token,
            "request_id": self.request_id,
            "nonce": self.nonce,
            "chain_id": self.chain_id,
            "sender": self.sender
        }

    def signable_bytes(self) -> bytes:
        return canonical_json_bytes(self.signable_dict())

    def sign(self, keypair: KeyPair) -> "Transaction":
        self.sender = keypair.public_key_hex
        self.signature = keypair.sign(self.signable_bytes())
        return self

    def verify(self) -> bool:
        if self.type == TransactionType.TICK:
            return True  # System ticks generated by leader during block proposal
        if not self.sender or not self.signature:
            return False
        return verify_signature(self.sender, self.signable_bytes(), self.signature)

    def tx_hash(self) -> str:
        data = self.model_dump()
        return sha256_hex(canonical_json_bytes(data))


class EventType(str, Enum):
    CREATED = "CREATED"
    GRANTED = "GRANTED"
    QUEUED = "QUEUED"
    RELEASED = "RELEASED"
    RENEWED = "RENEWED"
    EXPIRED = "EXPIRED"
    REJECTED = "REJECTED"


class Event(BaseModel):
    """
    State-transition event emitted by the Lock Manager during block execution.
    Subscribed to by the Gateway, Client SDKs, and Dashboard.
    """
    event: EventType
    semaphore: str
    holder: Optional[str] = None
    token: Optional[int] = None
    expires_at: Optional[int] = None
    block_height: Optional[int] = None
    timestamp: int
    details: Optional[Dict[str, Any]] = None


class HolderInfo(BaseModel):
    token: int
    owner: str
    expires_at: int
    request_id: str


class WaitRequest(BaseModel):
    owner: str
    request_id: str
    lease_ms: int


class SemaphoreSnapshot(BaseModel):
    name: str
    capacity: int
    holders: Dict[str, HolderInfo]      # token string -> HolderInfo
    queue: List[WaitRequest]
    next_token: int


class BlockHeader(BaseModel):
    height: int
    prev_hash: str
    merkle_root: str
    timestamp: int                     # Block time in milliseconds (consensus clock)
    proposer: str                      # Public key or validator ID of leader

    def header_hash(self) -> str:
        return sha256_hex(canonical_json_bytes(self.model_dump()))


class Block(BaseModel):
    header: BlockHeader
    transactions: List[Transaction]
    block_hash: str = ""

    def compute_hash(self) -> str:
        return self.header.header_hash()

    @classmethod
    def create(cls, height: int, prev_hash: str, timestamp: int,
               proposer: str, transactions: List[Transaction]) -> "Block":
        tx_hashes = [tx.tx_hash() for tx in transactions]
        merkle = MerkleTree(tx_hashes)
        header = BlockHeader(
            height=height,
            prev_hash=prev_hash,
            merkle_root=merkle.root,
            timestamp=timestamp,
            proposer=proposer
        )
        blk = cls(header=header, transactions=transactions)
        blk.block_hash = blk.compute_hash()
        return blk
